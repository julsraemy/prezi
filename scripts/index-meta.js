// Writes _includes/head-custom.html, which the Jekyll theme (Primer) puts at
// the end of the <head> of https://julsraemy.ch/prezi/ (README.md). From the
// front matter of every deck in md/ it generates:
//   - a schema.org JSON-LD @graph: the collection page and each presentation
//   - one COinS span per presentation, so Zotero offers the whole list
//
// No citation_* tags here: they describe a single work, and Zotero would save
// the index as one item instead of offering every presentation.
//
// Usage: node scripts/index-meta.js
const fs = require('fs')
const path = require('path')
const { frontMatter } = require('./citation-meta')

const mdDir = 'md'
const out = '_includes/head-custom.html'
const SITE = 'https://julsraemy.ch/prezi'
const ME = 'https://julsraemy.ch/#person'

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const plainNames = (s) => (s || '').split(/\s*,\s*|\s+and\s+|\s*&\s*/).filter(Boolean)
const isMe = (name) => /^Julien\b.*\bRaemy$/.test(name)

const decks = fs.readdirSync(mdDir)
  .filter((f) => f.endsWith('.md') && !f.startsWith('.'))
  .map((f) => {
    const fm = frontMatter(fs.readFileSync(path.join(mdDir, f), 'utf8'))
    const page = `${SITE}/${f.replace(/\.md$/, '.html')}`
    const doi = ((fm.url || '').match(/doi\.org\/(.+)$/i) || [])[1]
    return { ...fm, page, doi }
  })
  .filter((d) => d.title)
  .sort((a, b) => String(b.presented || '').localeCompare(String(a.presented || '')))

// --- schema.org JSON-LD --------------------------------------------------------
const person = (name) => (isMe(name) ? { '@id': ME } : { '@type': 'Person', name })

function node(d) {
  const n = {
    '@type': 'PresentationDigitalDocument',
    '@id': d.page,
    name: d.title,
    description: d.description,
    author: plainNames(d.author).map(person),
    datePublished: d.presented,
    inLanguage: d.lang || 'en',
    keywords: d.keywords,
    url: d.page,
    image: d.image,
    sameAs: d.doi ? `https://doi.org/${d.doi}` : undefined,
    identifier: d.doi ? { '@type': 'PropertyValue', propertyID: 'DOI', value: d.doi } : undefined,
    recordedAt: d.event ? {
      '@type': 'Event',
      name: d.event,
      startDate: d.presented,
      location: d.place ? (/^online$/i.test(d.place)
        ? { '@type': 'VirtualLocation', name: d.place }
        : { '@type': 'Place', name: d.place }) : undefined,
    } : undefined,
    isPartOf: { '@id': `${SITE}/` },
  }
  return JSON.parse(JSON.stringify(n)) // drop undefined values
}

const graph = {
  '@context': 'https://schema.org',
  '@graph': [
    {
      '@type': 'CollectionPage',
      '@id': `${SITE}/`,
      name: 'Slide decks by Julien A. Raemy',
      url: `${SITE}/`,
      author: { '@id': ME },
      hasPart: decks.map((d) => ({ '@id': d.page })),
    },
    { '@type': 'Person', '@id': ME, name: 'Julien A. Raemy', givenName: 'Julien A.', familyName: 'Raemy' },
    ...decks.map(node),
  ],
}

// --- COinS (OpenURL ContextObject in SPAN) -----------------------------------
// Zotero's OpenURL parser (zotero/utilities openurl.js): genre=document makes
// a document, whose title only rft.title sets (rft.btitle is ignored, and a
// span without a title is looked up by DOI or dropped); rft.type, read last,
// then turns it into a presentation.
function coins(d) {
  const p = new URLSearchParams()
  p.append('ctx_ver', 'Z39.88-2004')
  p.append('rft_val_fmt', 'info:ofi/fmt:kev:mtx:book')
  p.append('rft.genre', 'document')
  p.append('rft.title', d.title)
  for (const a of plainNames(d.author)) p.append('rft.au', a)
  if (d.presented) p.append('rft.date', d.presented)
  if (d.place && !/^online$/i.test(d.place)) p.append('rft.place', d.place)
  if (d.lang) p.append('rft.language', d.lang)
  if (d.description) p.append('rft.description', d.description)
  if (d.doi) p.append('rft_id', `info:doi/${d.doi}`)
  p.append('rft_id', d.page)
  p.append('rft.type', 'presentation')
  return `<span class="Z3988" title="${esc(p.toString())}"></span>`
}

const html = [
  '<!-- Generated by scripts/index-meta.js from the front matter in md/: do not edit -->',
  '{% raw %}',
  `<script type="application/ld+json">\n${JSON.stringify(graph, null, 2).replace(/</g, '\\u003c')}\n</script>`,
  ...decks.map(coins),
  '{% endraw %}',
  '',
].join('\n')

fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(out, html)
console.log(`${out}: ${decks.length} presentations`)
